def slug(word):
    tr = dict(zip("абвгдеёжзийклмнопрстуфхцчшщъыьэюя",
      ["a","b","v","g","d","e","yo","zh","z","i","y","k","l","m","n","o","p","r","s","t","u","f","h","c","ch","sh","sch","","y","","e","yu","ya"]))
    return "".join(tr.get(c, c) for c in word.lower()).replace(" ", "-")

def fetch(word):
    code = P[word]; fn = os.path.join(PICS, slug(word) + ".svg")
    if os.path.exists(fn): return "/assets/pics/" + slug(word) + ".svg"
    for c in (code, code + "-fe0f", code.replace("-fe0f", "")):
        url = f"https://cdn.jsdelivr.net/gh/jdecked/twemoji@15.1.0/assets/svg/{c}.svg"
        try:
            data = urllib.request.urlopen(url, timeout=30).read()
            if data.lstrip().startswith(b"<svg"):
                open(fn, "wb").write(data); return "/assets/pics/" + slug(word) + ".svg"
        except Exception:
            pass
    print("НЕТ КАРТИНКИ:", word, code); return ""

def pics(words): return [{"word": w, "pic": fetch(w)} for w in words]

