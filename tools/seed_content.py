HARD_V = ["а", "о", "у", "ы", "э"]; SOFT_V = ["я", "ё", "ю", "и", "е"]
def syl(cons, kind):
    c = cons
    if kind == "hard":
        op = [c + v for v in HARD_V]
        rows = ["-".join(op), "-".join(v + c for v in "аоуы"), "-".join("а" + c + v for v in "аоуы")]
    elif kind == "voiced":
        op = [c + v for v in HARD_V]
        rows = ["-".join(op), "-".join(v + c + v for v in "аоуы"), "-".join(c + v + c + v for v in "аоу")]
    elif kind == "soft":
        rows = ["-".join(c + v for v in SOFT_V), "-".join(v + c + "ь" for v in "аоуи") if c not in "зЗ" else "-".join(v + c + "и" for v in "аоу"),
                "-".join("а" + c + v for v in "яёюи")]
    elif kind == "sib":  # ш, ж, ц: и/е звучат твёрдо
        vs = ["а", "о", "у", "и", "е"] if c in "шж" else ["а", "о", "у", "ы", "е"]
        rows = ["-".join(c + v for v in vs), "-".join(v + c + v for v in "аоу"), "-".join(c + v + c + v for v in "аоу")]
    elif kind == "ch":
        rows = ["-".join(c + v for v in ["а", "о", "у", "и", "е"]), "-".join(v + c for v in "аоуи"), "-".join("а" + c + v for v in "аоуи")]
    return rows

def md(path, fm, body=""):
    with open(path, "w", encoding="utf8") as f:
        f.write("---\n" + yaml.safe_dump(fm, allow_unicode=True, sort_keys=False, width=1000) + "---\n" + body.strip() + "\n")

